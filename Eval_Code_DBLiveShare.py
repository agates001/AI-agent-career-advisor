import os
import streamlit as st
from dotenv import load_dotenv
from crewai import Agent, Task, Crew, LLM
from pydantic import BaseModel, Field
from supabase import create_client, Client

# Load OpenAI API Key from your local environment
load_dotenv()

# ========================================================
# Dashboard UI Setup
# ========================================================
st.set_page_config(page_title="MultiAgent/RAG App Auditor Dashboard", page_icon="", layout="centered")
st.title("Independent App Evaluation Dashboard")
st.write("This standalone program audits the output files generated by your main Multi-Agent/RAG application.")

# Define the strict structure the Judge must return
class EvaluationReport(BaseModel):
    score: int = Field(description="A score from 1 to 5 based strictly on the rubric criteria.")
    reasoning: str = Field(description="Detailed academic justification for the assigned score.")

# ========================================================
# Supabase Data Use
# ========================================================
def fetch_production_reports():
    """
    Pulls all multi-agent markdown reports live from your cloud database table.
    """
    url: str = os.environ.get("SUPABASE_URL")
    publishable_key: str = os.environ.get("SUPABASE_PUBLISHABLE_KEY") 
    
    if not url or not publishable_key:
        st.error("Missing Supabase environment variables! Check your local .env configuration.")
        return []
        
    try:
        from supabase import create_client, Client
        supabase: Client = create_client(url, publishable_key)
        # Fetching data sorted by the newest timestamp first, gathering report & resume text together
        response = supabase.table("agent_reports") \
            .select("id, agent_name, content, updated_at, resume_text") \
            .order("updated_at", desc=True) \
            .execute()
        return response.data
    except Exception as e:
        st.error(f"Failed to fetch production data from cloud: {e}")
        return []

# ========================================================
# Automated Auditing Pipeline Execution
# ========================================================
if st.button("Run Quality Audit on Latest App Output"):
    
    # A. Pull production report and resume text live from the Supabase Cloud
    with st.spinner("Fetching latest production run from Supabase Cloud..."):
        live_reports = fetch_production_reports()

    if not live_reports:
        st.warning("No records found in your cloud table. Please run your main app once to seed data.")
        st.stop()
        
    # Extract the single newest record row sitting at index 0
    newest_record = live_reports[0]
    
    # B. Extract both data pieces dynamically right from your database columns!
    generated_report_content = newest_record["content"]
    resume_text_content = newest_record["resume_text"]  
    report_id = newest_record["id"]
    report_time = newest_record["updated_at"]

    # Quick verification check to ensure the cloud row data is valid
    if not resume_text_content or not resume_text_content.strip():
        st.error("The retrieved resume text from the cloud was blank. Ensure your main app has populated this field.")
        st.stop()

    st.success(f"Connected! Successfully retrieved report [{report_id}] and resume synced at {report_time}.")

    # Display a clean data preview section for the auditor
    with st.expander("View Extracted Production Report", expanded=False):
        st.markdown(generated_report_content)

    # Spin up the isolated Judge infrastructure via CrewAI + gpt-4o-mini
    with st.spinner("Executing LLM-as-a-Judge analysis... Please wait..."):
        
        # Isolated judge model with 0.0 temperature for strict consistency
        judge_llm = LLM(model="openai/gpt-4o-mini", temperature=0.0)

        evaluator_agent = Agent(
            role="Senior Academic and Career Match Auditor",
            goal="Audit generated career reports to ensure job matches are logically aligned and course recommendations are completely faithful to the resume.",
            backstory="""You are an elite quality assurance auditor at a top-tier university. Your job is to catch AI hallucinations, logical gaps, and compliance failures. You have a zero-tolerance policy for career advisors that recommend courses a candidate has already completed or recommend jobs completely misaligned with their skill set.""",
            llm=judge_llm,
            verbose=True # Shows the judge's full thinking process in your local VSCode terminal
        )

        evaluation_task = Task(
            description=f"""Analyze the provided candidate resume text and the generated career report markdown file. 
            Evaluate the entire intelligence loop and grade the performance on a strict scale of 1 to 5 based on the rubric below:
            
            CRITICAL SCORING rubric:
            - 5 (Excellent): The suggested jobs closely match the candidate's technical background, skill gaps are highly accurate based on a structural comparison, and all recommended CU Boulder courses are completely new (un-taken).
            - 3 (Moderate): The job choices and course titles are relevant, but the logic explaining the skill gaps or course alignment is vague or overly generic.
            - 1 (Fail): The system committed a fatal error. This includes misaligning the candidate with jobs they don't qualify for, OR recommending a course that the candidate has ALREADY completed/taught on their resume.
            
            Candidate Resume Text:
            {resume_text_content}
            
            Generated Career Report File Content:
            {generated_report_content}
            """,
            expected_output="A structured evaluation report containing a 1-5 score and comprehensive reasoning.",
            agent=evaluator_agent,
            output_pydantic=EvaluationReport
        )

        eval_crew = Crew(
            agents=[evaluator_agent],
            tasks=[evaluation_task]
        )
        
        try:
            # Trigger the evaluation kickoff
            result = eval_crew.kickoff()
            
            # D. Display the Audit Metrics beautifully on the dashboard screen
            st.markdown("---")
            st.subheader("Final Quality Audit Metrics")
            
            col1, col2 = st.columns([1, 2])
            with col1:
                st.metric(label="Overall System Score", value=f"{result.pydantic.score} / 5")
            with col2:
                st.info(f"**Judge Decision Reasoning:** {result.pydantic.reasoning}")
                
        except Exception as e:
            st.error(f"The independent evaluation script encountered an error: {str(e)}")
